export function seedEntries() {
  const items = [
    ...affairs.map(([title, topic, summary], i) => ({ ...base("affairs", title, topic, i, reportSource), eventDate: "2026-03-05", dataPeriod: "2026 年政策安排；基于 2026 年政府工作报告", summary, examPoints: [summary, "区分预期目标、工作要求和已实现数据；这是历史报告考点，不是今日新闻。"] })),
    ...general.map(([title, topic, explanation], i) => ({ ...base("general", title, topic, i), concept: title, explanation })),
    ...idioms.map(([title, pronunciation, definition, collocation, example, term, difference], i) => ({ ...base("idiom", title, "用法辨析", i), pronunciation, definition, collocations: [collocation], example, confusableWith: [{ term, difference }] })),
    ...essays.map(([topic, sentence, paragraph, adaptation], i) => ({ ...base("essay", `${topic}：表达与展开`, topic, i), facts: ["本卡为原创写作示范，不作为现实事件或政策原文的证据。"], expressions: [sentence, paragraph], scenarios: [topic, "议论文分论点与对策展开"], aiSuggestions: [adaptation, "结合题目材料改写；示范句不是名人名言，不应冒充引用。"] })),
  ];
  const questions = items.filter(item => item.module !== "essay").map((item, index) => {
    const group = items.filter(other => other.module === item.module);
    const position = group.indexOf(item);
    const answer = item.summary ?? item.explanation ?? item.definition;
    const wrong = [1, 2, 3].map(offset => { const other = group[(position + offset) % group.length]; return other.summary ?? other.explanation ?? other.definition; });
    const texts = [...wrong]; texts.splice(index % 4, 0, answer);
    return { stableId: `${item.stableId}-practice`, revision: 1, knowledgeId: item.knowledgeId, module: item.module,
      prompt: `关于“${item.title}”，下列说明哪项正确？`, options: texts.map((text, i) => ({ id: "ABCD"[i], text })), correctOptionId: "ABCD"[index % 4],
      explanation: `${answer} 本题是原创概念识记练习，不是真题。`, sourceRefs: item.sourceRefs.map(source => source.id), reviewedAt: SEED_DATE, generatedByAi: true, label: "practice" };
  });
  return { items, questions };
}
